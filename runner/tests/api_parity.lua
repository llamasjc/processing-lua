-- stdout: ok
-- Processing API parity: constants, image and font methods on handles,
-- PVector, lists, dicts, Table, XML, PShape, matrices and paths.
local function near(a, b, eps) return math.abs(a - b) <= (eps or 1e-4) end

function setup()
  size(100, 100)

  -- constants
  assert(BURN == 8192 and OVERLAY == 512 and HAND == 12 and MAX_INT == 2147483647)
  assert(near(DEG_TO_RAD * 180, math.pi) and EPSILON == 0.0001 and LINE_STRIP == 50)
  assert(X == nil and Y == nil and Z == nil, "X, Y, Z stay free")
  cursor(HAND)

  -- images as objects
  local img = createImage(4, 2)
  assert(img.width == 4 and img.height == 2)
  img:set(1, 1, color(255, 0, 0))
  assert(red(img:get(1, 1)) == 255 and alpha(img:get(3, 0)) == 0)
  local part = img:get(1, 0, 2, 2)
  assert(part.width == 2 and red(part:get(0, 1)) == 255)
  img:loadPixels()
  assert(#img.pixels == 4 * 2 - 1 and red(img.pixels[1 * 4 + 1]) == 255)
  img.pixels[0] = color(0, 0, 255)
  img:updatePixels()
  assert(blue(img:get(0, 0)) == 255)
  local c = img:copy()
  assert(c ~= img and red(c:get(1, 1)) == 255)
  c:copy(img, 1, 1, 1, 1, 3, 0, 1, 1)
  assert(red(c:get(3, 0)) == 255)
  c:filter(INVERT)
  assert(red(c:get(3, 0)) == 0 and green(c:get(3, 0)) == 255)
  local m = createImage(4, 2)
  m:loadPixels() for i = 0, 7 do m.pixels[i] = color(128) end m:updatePixels()
  img:mask(m)
  assert(near(alpha(img:get(1, 1)), 128, 1))
  local base, top = createImage(2, 2), createImage(2, 2)
  base:set(0, 0, color(100)) top:set(0, 0, color(100))
  base:blend(top, 0, 0, 2, 2, 0, 0, 2, 2, ADD)
  assert(red(base:get(0, 0)) == 200)
  img:resize(8, 4)
  assert(img.width == 8 and img.height == 4)
  assert(img:save("parity.png") == true)
  assert(loadImage("parity.png").width == 8)
  local ok = pcall(function() return (5.5).width end)
  assert(not ok, "plain numbers can't be indexed")

  -- fonts
  local f = createFont("DejaVu Sans", 20)
  if f == 0 then f = createFont("sans-serif", 20) end
  if f ~= 0 then
    assert(f:getSize() == 20 and type(f:getName()) == "string")
    assert(f:ascent() > 0 and f:descent() > 0 and f:width("m") > 0)
    textFont(f)
  end

  -- PVector
  local v = createVector(3, 4)
  assert(v:equals(createVector(3, 4)) and not v:equals(createVector(1, 1)))
  local a = v:array()
  assert(a[1] == 3 and a[2] == 4 and a[3] == 0)
  assert(not rawequal(v:get(), v) and v:get():equals(v))
  v:setHeading(math.pi / 2)
  assert(near(v.x, 0) and near(v.y, 5) and near(v:heading2D(), math.pi / 2))
  assert(createVector(1, 2, 3):toString() == "[ 1, 2, 3 ]")

  -- lists
  local l = IntList(5, 1, 9, 1)
  l:appendUnique(9) l:appendUnique(7)
  assert(l:size() == 5 and l:maxIndex() == 2 and l:minIndex() == 1)
  assert(l:removeValues(1) == 2 and l:join(",") == "5,9,7")
  assert(l:replaceValue(9, 4) and l:replaceValues(3, 2) == 0)
  l:swap(0, 2)
  assert(l:join(",") == "7,4,5" and l:getSubset(1):join(",") == "4,5" and l:getSubset(0, 2):size() == 2)
  local pct = l:getPercent()
  assert(near(pct:get(0), 7 / 16))
  l:resize(5) assert(l:size() == 5 and l:get(4) == 0)
  assert(l:pop() == 0 and l:sumLong() == 16)
  assert(toJSON(IntList(1, 2)) == "[\n  1,\n  2\n]")
  local fl = FloatList(1.5, 2.5)
  assert(fl:hasValue(fl:random()) and fl:sumDouble() == 4.0)
  local sl = StringList("a", "b", "a", "c")
  assert(#sl:getUnique() == 3 and sl:getTally():get("a") == 2 and sl:getOrder():get("a") == 2)
  assert(sl:hasValue(sl:choice()))
  local n = sl:size() sl:removeChoice() assert(sl:size() == n - 1)
  assert(sl:array()[1] ~= nil)
  sl:save("list.txt")
  assert(#loadStrings("list.txt") == n - 1)

  -- dicts
  local d = IntDict({ apples = 3, pears = 1 })
  d:set("kiwi", 6)
  assert(d:index("pears") == 1 and d:index("nope") == -1)
  assert(d:maxIndex() == 2 and d:minIndex() == 1 and near(d:getPercent("kiwi"), 0.6))
  d:swap(0, 2)
  assert(d:key(0) == "kiwi")
  assert(d:removeIndex(0) == 6 and d:size() == 2)
  d:setIndex(0, "plums", 4)
  assert(d:get("plums") == 4 and not d:hasKey("pears") or d:key(0) == "plums")
  local seen = 0 for k, val in d:entries() do seen = seen + val end
  assert(seen == d:sum())
  local vals = 0 for val in d:values() do vals = vals + val end
  assert(vals == d:sumLong())
  d:resize(1) assert(d:size() == 1)
  assert(d:toJSON().plums == 4)

  -- Table
  local t = createTable("name", "score")
  for _, r in ipairs({ { "Ana", 9 }, { "Max", 30 }, { "Bo", 9 } }) do
    local row = t:addRow() row:setString("name", r[1]) row:setInt("score", r[2])
  end
  assert(t:getColumnIndex("score") == 1 and t:getColumnTitle(0) == "name" and t:hasColumnTitles())
  assert(t:findRowIndex("Max", "name") == 1 and #t:findRowIndices("9", "score") == 2)
  assert(t:matchRowIndex("^B", "name") == 2 and t:matchRow("a$", 0):getString("name") == "Ana")
  assert(#t:matchRows("[AB]", "name") == 2 and t:lastRowIndex() == 2)
  assert(t:getIntList("score"):sum() == 48 and t:getTally("score"):get("9") == 2)
  assert(t:getIntDict("name", "score"):get("Max") == 30 and #t:getUnique("score") == 2)
  assert(t:getStringRow(1)[1] == "Max" and t:getRowMap("name").Bo.index == 2)
  t:setColumnType("score", "int")
  assert(t:getColumnType(1) == 1 and t:getColumnTypes()[1] == 0)
  t:insertColumn(1, "team")
  assert(t:getColumnCount() == 3 and t:getInt(1, "score") == 30 and t:getString(0, "team") == "")
  t:setMissingString("-")
  assert(t:getString(0, "team") == "-")
  t:removeColumn("team")
  t:replace("Bo", "Bob")
  t:replaceAll("^(A)na$", "$1nna", "name")
  t:removeTokens("x")
  assert(t:getString(2, 0) == "Bob" and t:getString(0, 0) == "Anna")
  local t2 = t:copy()
  t2:addRows(t)
  assert(t2:getRowCount() == 6 and t:getRowCount() == 3)
  t2:insertRow(0, { "Zed", 1 })
  assert(t2:getString(0, "name") == "Zed" and t2:getLong(0, 1) == 1 and t2:getDouble(0, 1) == 1)
  t2:setRow(0, t:getRow(1))
  assert(t2:getString(0, 0) == "Ma", "removeTokens took the x")
  t2:setRowCount(2) assert(t2:getRowCount() == 2)
  t2:setColumnTitle(1, "points") assert(t2:getInt(1, "points") == 9)
  local row = t:getRow(0)
  assert(row:getColumnCount() == 2 and row:getColumnTitle(1) == "score" and row:getLong("score") == 9)
  row:setDouble("score", 2.5) assert(row:getDouble("score") == 2.5)
  local raw = createTable()
  raw:addColumn() raw:addColumn()
  local r0 = raw:addRow() r0:setString(0, "x") r0:setString(1, "y")
  local r1 = raw:addRow() r1:setString(0, "1") r1:setString(1, "2")
  raw:removeTitleRow()
  assert(raw:getRowCount() == 1 and raw:getInt(0, "y") == 2)
  assert(t:save("t.csv") and loadTable("t.csv", "header"):getString(1, "name") == "Ma")

  -- XML
  local x = parseXML('<a xmlns:p="u"><p:b n="12345678901" f="2.5"> hi </p:b></a>')
  local b = x:getChild("p:b")
  assert(b:getLocalName() == "b" and b:getParent() == x)
  assert(b:getLong("n") == 12345678901 and b:getDouble("f") == 2.5)
  b:trim() assert(b:getContent() == "hi")
  b:setLong("n", 7) b:setDouble("f", 0.5)
  assert(b:getInt("n") == 7 and b:getFloat("f") == 0.5)
  b:setIntContent(42) assert(b:getLongContent() == 42)
  b:setFloatContent(1.5) assert(b:getDoubleContent() == 1.5)
  local kid = x:addChild("c") assert(kid:getParent() == x)
  assert(x:save("x.xml") and loadXML("x.xml"):getChild("c") ~= nil)

  -- PShape
  local s = createShape()
  s:beginShape(TRIANGLES)
  s:fill(255, 0, 0)
  s:vertex(0, 0) s:vertex(10, 0, 5, 6) s:vertex(0, 10)
  s:endShape(CLOSE)
  assert(s:getKind() == TRIANGLES and s:getFamily() == PShape.PATH and s:isClosed())
  assert(s:getVertexX(1) == 10 and s:getTextureU(1) == 5 and s:getTextureV(1) == 6 and s:getVertexZ(0) == 0)
  assert(s:getVertexCodeCount() == 3 and s:getVertexCode(0) == VERTEX)
  assert(red(s:getFill()) == 255 and s:getStroke() == nil and s:is2D() and not s:is3D())
  assert(s:contains(2, 2) and not s:contains(20, 20))
  s:setStrokeCap(ROUND) s:setTint(255, 128) s:setShininess(5)
  assert(s:getShininess() == 5 and alpha(s:getTint()) == 128)
  s:setName("tri") s:setVisible(false)
  assert(not s:isVisible())
  shape(s, 0, 0)
  local r = createShape(RECT, 1, 2, 30, 40)
  assert(r:getFamily() == PShape.PRIMITIVE and r:getKind() == RECT and r:getParam(2) == 30)
  local g = createShape(GROUP)
  g:addChild(s) g:addChild(r)
  assert(g:getFamily() == GROUP and g:findChild("tri") == s and s:getParent() == g)
  assert(g:getChildIndex(r) == 1 and #g:getChildren() == 2)
  g:removeChild(0) assert(g:getChildCount() == 1)
  r:applyMatrix(1, 0, 5, 0, 1, 5)
  shape(g, 0, 0)

  -- matrices
  assert(is2D() and not is3D())
  pushMatrix()
  translate(10, 20)
  local mm = getMatrix()
  assert(mm.m02 == 10 and mm.m12 == 20 and mm.m00 == 1)
  mm:rotate(math.pi / 2)
  local p = mm:mult(createVector(1, 0))
  assert(near(p.x, 10) and near(p.y, 21))
  resetMatrix()
  setMatrix(mm)
  local back = getMatrix()
  assert(near(back.m02, 10) and near(back.m01, -1))
  resetMatrix()
  applyMatrix(1, 0, 7, 0, 1, 3)
  assert(near(getMatrix().m02, 7) and near(getMatrix().m12, 3))
  local inv = PMatrix2D(2, 0, 4, 0, 2, 6)
  assert(inv:invert() and near(inv.m00, 0.5) and near(inv.m02, -2))
  local m3 = PMatrix3D()
  m3:translate(1, 2, 3) m3:rotateX(0.3)
  local i3 = m3:get() assert(i3:invert())
  i3:apply(m3) assert(near(i3.m00, 1) and near(i3.m03, 0) and near(i3.m23, 0))
  popMatrix()

  -- paths and the rest
  assert(sketchPath() ~= "" and dataPath("a.png"):match("data[/\\]a%.png$"))
  assert(savePath("out/z.txt"):match("out[/\\]z%.txt$"))
  local found = false
  for _, path in ipairs(listFiles(".")) do if path:match("parity%.png$") then found = true end end
  assert(found)
  assert(listPaths("no-such-dir")[1] == nil)
  assert(isLooping())
  noLoop() assert(not isLooping()) loop()
  orientation(LANDSCAPE)

  print("ok")
  exit()
end
