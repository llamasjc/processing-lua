-- JSON objects and arrays answer Processing's methods; Long/Double lists; multW
-- stdout: ok
local o = parseJSONObject('{"id": 7, "name": "pep", "on": true, "pts": [1, 2.5, "3"], "sub": {"k": 1}}')
assert(o:getInt("id") == 7 and o:getString("name") == "pep" and o:getBoolean("on"))
assert(o:hasKey("sub") and not o:hasKey("nope") and o:isNull("nope"))
assert(o:getJSONObject("sub"):getInt("k") == 1)
local a = o:getJSONArray("pts")
assert(a:size() == 3 and a:getFloat(1) == 2.5 and a:getInt(2) == 3)
assert(a:toIntList():get(1) == 2)
assert(o:getInt("missing", 5) == 5)
assert(not pcall(function() return o:getInt("missing") end))
local j = JSONObject():setInt("x", 3):setString("s", "hi")
j:setJSONArray("list", JSONArray():append(1):append("two"))
local back = parseJSONObject(j:format(-1))
assert(back:getInt("x") == 3 and back:getJSONArray("list"):getString(1) == "two")
assert(toJSON(JSONObject()) ~= "[]" and toJSON(JSONArray()) == "[]")
assert(#o:keys() == 5 and o.name == "pep" and o.pts[1] == 1)
local l = LongList() l:append(2) l:append(5)
assert(l:sum() == 7 and DoubleDict ~= nil)
local m = PMatrix3D()
assert(m:multW(1, 2, 3) == 1 and m:multZ(1, 2, 3) == 3)
local c = m:cmult(createVector(1, 2, 3))
assert(c.x == 1 and c.z == 3)
